import Cocoa

// ============================================================================
// 自动切换输入法 (AutoSwitchInput)
// 按应用（以及应用内的具体位置）自动切换输入法
//
//  1. 永不缓存 TISInputSource —— 输入法重启后旧引用会静默失效，每次按 ID 重查
//  2. 三重触发：应用激活 / 焦点元素变化(AX) / 定时看门狗
//  3. 切换后多轮校验 + 重试，对付「目标 App 抢回自己的输入法」的竞态
//  4. 识别用户手动切换并学习，避免和用户对着干
//  5. 安全键盘输入（密码框）期间主动跳过，不打断系统行为
//
// 代码分层（src/）：
//   Core     路径、日志、本地化、常量
//   Input    TIS 封装、AX 读取、焦点探测、应用索引
//   Model    配置结构与读写、规则匹配、输入法判定
//   Runtime  切换引擎、触发源、开机启动
//   UI       设置窗口、菜单栏面板、状态栏菜单、截图
//   App      内核（AppController）、生命周期、调试钩子
// ============================================================================

let app = NSApplication.shared
let delegate = AppDelegate()
app.delegate = delegate
app.run()
